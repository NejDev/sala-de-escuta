"""Writes spotify_assistant/medal_names.py from the achievements catalog's tables (names and "how" lines).

    python scripts/make_medal_names.py [repo root]

The root defaults to the repository this script is in. SPOILERS: the catalog and the module it writes name every
medal and say how each one is earned.
"""
import json
import re
import sys
from pathlib import Path

CATALOG = "docs/superpowers/specs/2026-10-15-achievements-catalog.md"
MODULE = "spotify_assistant/medal_names.py"


def main(repo: Path) -> None:
    catalog = (repo / CATALOG).read_text(encoding="utf-8")
    section = catalog.split("## Medals", 1)[1].split("## Code", 1)[0]
    names: dict[str, dict[str, str]] = {"pt": {}, "en": {}}
    for line in section.splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) != 6 or not re.fullmatch(r"[a-z0-9][a-z0-9-]*", cells[0]) or cells[0] == "id":
            continue
        medal_id, _, pt, en, how_pt, how_en = cells
        names["pt"][f"medal.{medal_id}"], names["en"][f"medal.{medal_id}"] = pt, en
        names["pt"][f"medal.{medal_id}.how"], names["en"][f"medal.{medal_id}.how"] = how_pt, how_en
    lines = [
        '"""Medal names and "how" lines. SPOILERS: generated by scripts/make_medal_names.py from',
        f"{CATALOG}.",
        "",
        'i18n merges them into MESSAGES; a "how" line only ever reaches whoever earned the medal.',
        '"""',
        "",
        "NAMES: dict[str, dict[str, str]] = {",
    ]
    for lang in ("pt", "en"):
        lines.append(f'    "{lang}": {{')
        lines += [f"        {json.dumps(key)}: {json.dumps(text, ensure_ascii=False)}," for key, text in names[lang].items()]
        lines.append("    },")
    lines.append("}")
    with open(repo / MODULE, "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines) + "\n")
    print(len(names["pt"]) // 2, "medals")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent)
